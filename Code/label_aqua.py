aqua_l8 = pd.read_csv("/home/tmalik6/LLMR/Code/hllm/training_data/AQUA_Llama_8B_train.csv")
aqua_l70 = pd.read_csv("/home/tmalik6/LLMR/Code/hllm/training_data/AQUA_L70_train.csv")

aqua_big_df = aqua_l8.merge(aqua_l70, on="Question")

print(aqua_big_df.columns)
aqua_big_df = aqua_big_df.drop("Unnamed: 0_x", axis=1)
