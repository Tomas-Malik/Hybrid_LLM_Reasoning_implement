aqua_big_df = aqua_big_df.drop("Correct Answer_y", axis=1)

aqua_big_df["dataset"] = "aqua"
print(aqua_big_df.columns)

aqua_big_df = aqua_big_df.rename(columns={
    "Correct Answer_x": "Answer",
    "Llama_8B Full": "l8",
    "L70 Full": "l70"
})

print(aqua_big_df.columns)


df_og = aqua_big_df


questions = df_og["Question"].to_list()

answers = df_og["Answer"].to_list()
l8_full = df_og["l8"].to_list()
l70_full = df_og["l70"].to_list()
dataset = df_og["dataset"].to_list()


lean_l8 = []
lean_l70 = []

l8_on_cor_l70_on_incor = []

l = 0

l8_fail = 0
l70_fail = 0
target_fail =0

for q, ans, l8, l70, ds in tqdm(zip(questions, answers, l8_full, l70_full, dataset),total=len(questions), desc = "Running..."):
    l+=1

    
    
    l8_ans = extract_final_letter(l8, q)

    if l8_ans == "fail":
        l8_fail +=1
    l70_ans = extract_final_letter(l70, q)
    if l70_ans == "fail":
        l70_fail +=1
    target = ans
    

    if (l70_ans == target) and (l8_ans == target):
        lean_l8.append(1)
        lean_l70.append(0)
        l8_on_cor_l70_on_incor.append(1)
    elif (l70_ans == target):
        lean_l8.append(0)
        lean_l70.append(0)
        l8_on_cor_l70_on_incor.append(0)
    elif (l8_ans == target):
        lean_l8.append(1)
        lean_l70.append(1)
        l8_on_cor_l70_on_incor.append(1)
    else:
        lean_l8.append(1)
        lean_l70.append(0)
        l8_on_cor_l70_on_incor.append(0)



df_labeled = df_og
